import { readdir, readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const counts = new Map()

async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const file = new URL(entry.name + (entry.isDirectory() ? '/' : ''), directory)
    if (entry.isDirectory() && !entry.name.includes('test')) await collect(file)
    else if (entry.isFile() && /\.(vue|ts)$/.test(entry.name)) {
      const source = await readFile(file, 'utf8')
      for (const character of source.match(/[\u3000-\u303f\u3400-\u9fff\uff00-\uffef]/g) || []) {
        counts.set(character, (counts.get(character) || 0) + 1)
      }
    }
  }
}

async function download(url) {
  const response = await fetch(url, {
    headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36' },
    signal: AbortSignal.timeout(30000)
  })
  if (!response.ok) throw new Error(`Workspace font request failed: ${response.status}`)
  return response
}

await collect(new URL('src/', root))
// Common characters share a subset, so most workspace screens need only the first files.
const characters = [...counts].sort((a, b) => b[1] - a[1] || a[0].codePointAt(0) - b[0].codePointAt(0)).map(([character]) => character)
const subsets = []
for (let offset = 0; offset < characters.length; offset += 512) {
  const group = characters.slice(offset, offset + 512)
  const css = await (await download('https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@400;500;600;700&display=swap&text=' + encodeURIComponent(group.join('')))).text()
  const urls = [...new Set([...css.matchAll(/url\(([^)]+)\)/g)].map(match => match[1]))]
  if (urls.length !== 1) throw new Error('Expected one variable font URL for each subset')
  const font = Buffer.from(await (await download(urls[0])).arrayBuffer())
  if (font.subarray(0, 4).toString() !== 'wOF2') throw new Error('Expected WOFF2')
  subsets.push({ font, group })
}

let rules = '/* Generated by scripts/update-workspace-font.mjs; Noto Sans SC, SIL OFL. */\n'
for (let index = 0; index < subsets.length; index++) {
  const { font, group } = subsets[index]
  const filename = `workspace-sans-sc-${index}.woff2`
  await writeFile(new URL(`public/brand/${filename}`, root), font)
  const range = group.map(character => `U+${character.codePointAt(0).toString(16).toUpperCase()}`).join(', ')
  rules += `@font-face {\n  font-family: 'Gabugu Sans SC';\n  font-style: normal;\n  font-weight: 400 700;\n  font-display: swap;\n  src: url('/brand/${filename}') format('woff2');\n  unicode-range: ${range};\n}\n`
}
await writeFile(new URL('src/styles/workspace-fonts.css', root), rules)
console.log(`Workspace font: ${characters.length} characters in ${subsets.length} subsets, ${subsets.reduce((total, item) => total + item.font.length, 0)} bytes. License: public/brand/noto-sans-sc-OFL.txt`)
